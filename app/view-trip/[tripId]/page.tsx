"use client";
import type { TripInfo } from "@/app/create-new-trip/_components/ChatBox";
import { useTripDetail } from "@/app/provider";
import { ResizablePanel, ResizablePanelGroup, ResizablePanelResizeHandle } from "@/components/ui/resizable";
import { api } from "@/convex/_generated/api";
import { useMediaQuery } from "@/hooks/use-media-query";
import { extractCoordinates } from "@/lib/trip-coordinates";
import { useQuery } from "convex/react";
import { ListOrdered, Map } from "lucide-react";
import dynamic from "next/dynamic";
import { useParams } from "next/navigation";
import { useEffect, useRef, useState } from "react";
import { useReactToPrint } from "react-to-print";
import Itinerary from "../_components/Itinerary";
import SavedPlacesSection from "../_components/SavedPlacesSection";
import TripHeader from "../_components/TripHeader";
import WeatherSection from "../_components/WeatherSection";

const GlobalMap = dynamic(() => import("@/app/create-new-trip/_components/GlobalMap"), { ssr: false });

export default function ViewTrip() {
  const { tripId } = useParams<{ tripId: string }>();
  const trip = useQuery(api.tripDetail.GetTrip, { tripId });
  const { setTripDetailInfo } = useTripDetail();
  const details = (trip?.tripDetail as TripInfo | undefined) ?? null;
  const componentRef = useRef<HTMLDivElement>(null);
  const scrollRef = useRef<HTMLDivElement>(null);
  const isDesktop = useMediaQuery("(min-width: 1024px)");
  const [mobileView, setMobileView] = useState<"itinerary" | "map">("itinerary");
  const handlePrint = useReactToPrint({ contentRef: componentRef });
  useEffect(() => { setTripDetailInfo(details); }, [details, setTripDetailInfo]);
  const firstActivity = details?.itinerary?.flatMap((day) => day.activities ?? day.places ?? (Array.isArray(day.plan) ? day.plan : []))[0];
  const location = extractCoordinates(firstActivity?.geo_coordinates);
  const coordinates = location ? { lat: location[1], lng: location[0] } : undefined;

  if (trip === undefined) return <main className="page-shell"><p role="status" className="text-muted-foreground">Loading your itinerary…</p></main>;
  if (!trip) return <main className="page-shell"><h1 className="text-3xl font-semibold">Trip not found</h1><p className="mt-4 text-muted-foreground">This trip may no longer be available.</p></main>;

  const itinerary = <div ref={scrollRef} className="h-full overflow-y-auto overscroll-contain">
    <div ref={componentRef} className="px-4 pb-10 pt-5 sm:px-6 lg:px-8">
      <TripHeader trip={details} onPrint={handlePrint} />
      <div className="mt-8 space-y-6">
        <WeatherSection coordinates={coordinates} />
        <h2 className="text-2xl font-semibold tracking-tight">Your plan, day by day</h2>
        <Itinerary scrollContainer={scrollRef} />
        <SavedPlacesSection />
      </div>
      <div className="hidden p-10 text-center text-sm text-gray-400 print:block">Generated by SmartJourney AI</div>
    </div>
  </div>;

  return <main className="fixed inset-x-0 bottom-0 top-[var(--header-h)] flex min-h-0 flex-col overflow-hidden">
    {isDesktop ? <ResizablePanelGroup orientation="horizontal" className="h-full">
      <ResizablePanel defaultSize={60} minSize={40}>{itinerary}</ResizablePanel>
      <ResizablePanelResizeHandle className="w-2 bg-border transition-colors hover:bg-primary" />
      <ResizablePanel defaultSize={40} minSize={25}><GlobalMap /></ResizablePanel>
    </ResizablePanelGroup> : <>
      <nav aria-label="Trip views" className="flex shrink-0 gap-2 border-b border-border bg-background p-3">
        {([['itinerary', 'Itinerary', ListOrdered], ['map', 'Map', Map]] as const).map(([value, label, Icon]) => <button key={value} type="button" aria-pressed={mobileView === value} onClick={() => setMobileView(value)} className={`flex min-h-11 flex-1 items-center justify-center gap-2 rounded-xl text-sm font-medium transition-colors ${mobileView === value ? 'bg-primary text-white' : 'bg-card text-muted-foreground hover:text-foreground'}`}><Icon size={16} />{label}</button>)}
      </nav>
      <div className={`min-h-0 flex-1 ${mobileView === 'itinerary' ? 'block' : 'hidden'}`}>{itinerary}</div>
      <div className={`min-h-0 flex-1 ${mobileView === 'map' ? 'block' : 'hidden'}`}><GlobalMap active={mobileView === 'map'} /></div>
    </>}
  </main>;
}
